import re
from typing import Optional
from modules.llm_client import GeminiClient

def sanitize_for_gemini(text: str) -> str:
    """Мягко сглаживает триггерные формулировки (порнографические/чрезмерно жестокие маркеры),
    которые вызывают жёсткую блокировку PROHIBITED_CONTENT у нейросети Google, сохраняя весь документальный смысл."""
    if not text:
        return ""
    patterns = [
        (r'фотографировать\s+(?:себя\s+)?обнаженным', 'сделать снимки'),
        (r'сфотографировать\s+(?:себя\s+)?обнаженным', 'сделать снимки'),
        (r'позволить\s+сфотографировать\s+себя\s+обнаженным', 'попозировать для фото'),
        (r'попеременно\s+то\s+насиловал\s+[^,\.\n]+', 'удерживал жертву силой и издевался'),
        (r'насиловал\s+[^,\.\n]+', 'удерживал жертву силой'),
        (r'приставив\s+его\s+к\s+паху', 'угрожая холодным оружием'),
        (r'съесть\s+сердце', 'расправиться с жертвой'),
        (r'вырезать\s+сердце', 'расправиться со мной'),
    ]
    cleaned = text
    for pat, rep in patterns:
        cleaned = re.sub(pat, rep, cleaned, flags=re.IGNORECASE)
    return cleaned

SYSTEM_SCRIPT_WRITER_PROMPT = """
Ты — главный режиссер-сценарист и шоураннер топовых YouTube-документалок и познавательных каналов с миллионными просмотрами (в стиле Lemmino, Magnates Media, Kurzgesagt, Johnny Harris, Veritasium, Netflix Documentary).

Твоя задача: превратить тему, факты и исходные материалы в мощный кинематографичный сценарий для длинного видео (10-30 минут) в заданном жанре.

КЛЮЧЕВЫЕ ПРАВИЛА И СТАНДАРТЫ УДЕРЖАНИЯ YOUTUBE:
1. «Зеленая монетизация» (Safe YouTube Policy):
   - Первые 30-60 секунд (Хук) — зона максимального удержания аудитории.
   - СТРОГО ЗАПРЕЩЕНО использовать деструктивные слова-триггеры демонетизации («убийство», «труп», «кровь», «расчленил», «насилие»).
   - Делай ставку на ПАРАДОКС, интригу, тайну, масштаб событий, конфликт интересов или неожиданный вопрос («Как один человек изменил целую индустрию?», «Почему проект за миллиарды рухнул за день?»).

2. Драматургия и структура:
   - Дели сценарий на четкие логические Акты (Акт I. Завязка и парадокс -> Акт II. Развитие событий и контекст -> Акт III. Поворотный момент / Расследование -> Акт IV. Кульминация и последствия -> Акт V. Выводы, этический вопрос и будущее).
   - Каждые 3-4 минуты формулируй микро-клиффхэнгер или интригующий переход (точки удержания перед рекламными паузами).
   - Финал (Аутро) оставляет сильное послевкусие, задает открытый вопрос зрителям для стимуляции сотен комментариев и органично предлагает подписаться.

3. Форматирование текста (Двухколоночный режиссерский сценарий):
   Сценарий оформляется структурированными блоками или таблицами:
   - [Тайминг]: приблизительные временные рамки сцены.
   - [Видеоряд и графика]: детальные указания для монтажера (карты, 3D схемы, макро-кадры, архивные фото, документы, графики, таймлайн).
   - [Аудиоряд и SFX]: саунд-дизайн (Sub-bass, эмбиент, нарастающий ритм, щелчки) + ТЕКСТ ДИКТОРА.

4. Разметка дикторского текста (Voiceover Script):
   - `[Пауза — Х сек]` — паузы дыхания и нагнетания атмосферы.
   - **Жирный шрифт** — смысловые ударения голосом.
   - `(В скобках курсивом)` — указания диктору по интонации (сдержанно, интригующе, динамично, с иронией, торжественно).
   - Темп речи: 130-140 слов в минуту. Текст звучит живо, гладко и захватывающе.
"""

class ScriptGenerator:
    def __init__(self, model_name: Optional[str] = None):
        self.llm = GeminiClient(model_name=model_name)

    def generate_outline(self, source_materials: str, topic: str = "", custom_instructions: str = "") -> str:
        """
        Шаг 1: Формирует структурный план глав по тексту первоисточников
        по строгому авторскому промпту удержания.
        """
        clean_materials = sanitize_for_gemini(source_materials)
        prompt = f"""
Создай для этого текста структурный план глав, по которому мы в дальнейшем будем последовательно и подробно раскрывать информацию по этой статье, но другими словами, пересказывая ее. Твоя задача сделать структурный план таким, чтобы он удерживал максимальное количество внимания зрителя, чтобы он остался до конца. Глава не должна обрываться резко, одна глава будет продолжаться следующей до самого конца.

ТЕМА ВИДЕО: {topic if topic else "По материалам текста"}

ИСХОДНЫЙ ТЕКСТ / СТАТЬЯ:
{clean_materials if clean_materials.strip() else "Сформируй план на основе темы: " + topic}

{f"ДОПОЛНИТЕЛЬНЫЕ ПОЖЕЛАНИЯ: {custom_instructions}" if custom_instructions else ""}

ТРЕБОВАНИЯ К ФОРМАТУ ВЫВОДА:
Выведи нумерованный список глав от 1 до N (обычно 4-8 глав).
Для каждой главы укажи:
1. Номер и яркое интригующее название
2. Краткую суть и конфликт этой главы (1-2 предложения)
Каждая глава должна быть на отдельной строке с цифрой, например:
1. Заголовок главы — Краткое описание интриги и событий.
"""
        return self.llm.generate(prompt=prompt, system_prompt=SYSTEM_SCRIPT_WRITER_PROMPT, temperature=0.7)

    @staticmethod
    def parse_outline_chapters(outline_text: str) -> list[str]:
        """Парсит текст плана на отдельные главы/пункты."""
        chapters = []
        for line in outline_text.splitlines():
            line_str = line.strip()
            # Ищем строки, начинающиеся с цифры: "1. ", "1)", "Глава 1:" или маркеры
            if re.match(r'^(?:\d+[\.\)]|глава\s*\d+[:\.]?|###\s*\d+[\.\)])\s+', line_str, flags=re.IGNORECASE):
                chapters.append(line_str)
        # Если регулярка не нашла нумерацию, делим по непустым строкам
        if not chapters:
            chapters = [l.strip() for l in outline_text.splitlines() if len(l.strip()) > 10 and not l.strip().startswith('#')]
        return chapters

    def generate_chapter_text(
        self,
        chapter_title: str,
        outline_text: str,
        source_materials: str,
        min_chars_per_chapter: int = 3500,
        previous_context: str = "",
        custom_instructions: str = ""
    ) -> str:
        """
        Шаг 2: Пишет текст отдельной главы по строгому авторскому промпту.
        Генерирует исключительно чистую дикторскую речь заданного объема без режиссерских пометок.
        """
        clean_materials = sanitize_for_gemini(source_materials)
        
        context_block = ""
        if previous_context.strip():
            tail = previous_context.strip()[-800:]
            context_block = f"""
КОНТЕКСТ ПРЕДЫДУЩЕГО ПОВЕСТВОВАНИЯ (на чем закончился предыдущий фрагмент, продолжи плавно, естественно и без швов):
«...{tail}»
"""

        min_words = max(250, int(min_chars_per_chapter / 7.5))

        prompt = f"""
Ты — профессиональный сценарист-рассказчик топовых документальных YouTube-фильмов.
Твоя задача — писать ИСКЛЮЧИТЕЛЬНО готовый связный дикторский текст для озвучки (только непрерывная литературная речь диктора).
СТРОГО ЗАПРЕЩЕНО добавлять блоки [Видеоряд], [Аудиоряд], таймкоды [00:00], таблицы, указания монтажеру и служебные заголовки. Пиши только чистый связный текст для начитки голосом.

ОБЯЗАТЕЛЬНОЕ ТРЕБОВАНИЕ К ОБЪЕМУ:
Данная глава должна содержать НЕ МЕНЕЕ {min_chars_per_chapter} знаков (примерно не менее {min_words} слов) чистого связного дикторского повествования. 
Подробно, шаг за шагом раскрывай каждую деталь, факты, психологию участников, атмосферу происходящего и нарастающее напряжение, чтобы зритель слушал не отрываясь.

СТРУКТУРНЫЙ ПЛАН ВСЕХ ГЛАВ:
{outline_text}

{context_block}

ИСХОДНЫЙ ТЕКСТ / СТАТЬЯ:
{clean_materials[:12000]}

{f"ДОПОЛНИТЕЛЬНЫЕ ПОЖЕЛАНИЯ: {custom_instructions}" if custom_instructions else ""}

ПРАВИЛА НАПИСАНИЯ:
Текст должен содержать не менее {min_chars_per_chapter} знаков. Теперь начинаем писать на основе изначального текста и структурного плана глав, который ты предложил. Повествование должно быть последовательное, цельное и динамичное. Текст должен быть написан так, чтобы условное разделение служило лишь организационной рамкой, а сам текст читался как единое непрерывное произведение без явных обозначений «глава», «раздел» или подведения итогов в конце каждой части.   
На протяжении всей этой статьи не повторяйся (не озвучивай одинаковые факты, главы или какую либо другую повторяющуюся информацию). Текст нужно писать так, чтобы удерживать максимальное внимание зрителя и не потерять его в самом начале, а довести до конца. Слова вроде "смерть", "секс", "умер", "порно" заменяй более нейтральными. Также имей ввиду, что полученный текст должно быть удобно озвучить ИИ роботу.

Начинаем писать с:
{chapter_title}
"""
        return self.llm.generate(prompt=prompt, system_prompt=None, temperature=0.75)

    def generate_script_by_chapters(
        self,
        outline_text: str,
        source_materials: str,
        min_chars_per_chapter: int = 3500,
        custom_instructions: str = "",
        progress_callback = None
    ) -> str:
        """
        Последовательно генерирует весь сценарий глава за главой,
        обеспечивая необходимый суммарный объем и плавные переходы.
        """
        chapters = self.parse_outline_chapters(outline_text)
        if not chapters:
            chapters = [outline_text]

        full_parts = []
        total = len(chapters)

        for i, chapter in enumerate(chapters):
            if progress_callback:
                progress_callback(i, total, chapter)
            
            prev_ctx = "\n\n".join(full_parts)
            part_text = self.generate_chapter_text(
                chapter_title=chapter,
                outline_text=outline_text,
                source_materials=source_materials,
                min_chars_per_chapter=min_chars_per_chapter,
                previous_context=prev_ctx,
                custom_instructions=custom_instructions
            )
            full_parts.append(part_text.strip())

        return "\n\n".join(full_parts)

    def generate_script(
        self,
        topic: str,
        source_materials: str,
        target_minutes: int = 15,
        genre: str = "Документальное расследование",
        custom_instructions: str = ""
    ) -> str:
        """Классический однопроходный генератор сценария."""
        words_target = target_minutes * 135
        clean_materials = sanitize_for_gemini(source_materials)
        
        prompt = f"""
Создай полный, высококачественный режиссерский сценарий для видео на YouTube.

ТЕМА: {topic}
ЖАНР / НАПРАВЛЕНИЕ: {genre}
ЖЕЛАЕМЫЙ ХРОНОМЕТРАЖ: ~{target_minutes} минут (примерно {words_target} слов начитки)

ИСХОДНЫЕ МАТЕРИАЛЫ И ФАКТЫ:
{clean_materials if clean_materials.strip() else "Опирайся на достоверные факты, историю и ключевые события по теме."}

ДОПОЛНИТЕЛЬНЫЕ ПОЖЕЛАНИЯ:
{custom_instructions if custom_instructions else "Максимальная драматургия, четкая разбивка на акты, готовый текст для начитки с паузами и ударениями."}

ТРЕБОВАНИЯ К ВЫВОДУ:
1. Заголовок и идея для ролика.
2. Архитектура таймлайна (краткий план по минутам).
3. Полный режиссерский сценарий с разбивкой по Актам и сценам, с двухколоночным форматом (Тайминг | Видеоряд и SFX | Текст диктора с пометками и ударениями).
4. Вовлекающее аутро с вопросом для комментариев.
5. ОБЯЗАТЕЛЬНЫЙ РАЗДЕЛ В КОНЦЕ:
   Создай раздел `### ЧИСТЫЙ ТЕКСТ ДЛЯ ОЗВУЧКИ:`, в котором слитными связными абзацами приведи ТОЛЬКО чистую литературную речь диктора от первого до последнего слова, без единой таблицы, без таймкодов, без слов "Кадр 1/SFX/Диктор" и без спецсимволов.
"""
        return self.llm.generate(prompt=prompt, system_prompt=SYSTEM_SCRIPT_WRITER_PROMPT, temperature=0.7)
